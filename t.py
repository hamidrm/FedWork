#!/usr/bin/env python3
"""FedWork BNN: accuracy versus *bidirectional* communication.

Reads trusted *probes_data.data files produced by FedWork's utils/profiler.py.
No imputation of missing metrics, no invented measurements.

Usage:
    python analyze_fedbnn.py --input-dir ./output --out ./analysis
    python analyze_fedbnn.py --file FedBop=/path/FedBopVGG7_probes_data.data \
        --file FedVote=/path/FedVoteVGG7_probes_data.data --out ./analysis

WARNING: pickle / torch serialization can execute arbitrary Python. Only load
probe files generated by a system you trust.
"""
